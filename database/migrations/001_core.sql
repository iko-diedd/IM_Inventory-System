CREATE FUNCTION current_app_role() RETURNS app_role
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT role FROM public.app_profiles
    WHERE user_id = auth.uid() AND is_active
$$;
REVOKE ALL ON FUNCTION current_app_role() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION current_app_role() TO authenticated;

CREATE POLICY profiles_read_self_or_admin ON app_profiles FOR SELECT TO authenticated
USING (user_id = auth.uid() OR current_app_role() = 'administrator');
CREATE POLICY products_read_authenticated ON products FOR SELECT TO authenticated USING (true);
CREATE POLICY categories_read_authenticated ON categories FOR SELECT TO authenticated USING (true);
CREATE POLICY brands_read_authenticated ON brands FOR SELECT TO authenticated USING (true);
CREATE POLICY suppliers_read_inventory_roles ON suppliers FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY purchases_read_inventory_roles ON purchases FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY purchase_items_read_inventory_roles ON purchase_items FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY purchase_receipts_read_inventory_roles ON purchase_receipts FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY purchase_receipt_items_read_inventory_roles ON purchase_receipt_items FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY sales_read_authorized ON sales FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager') OR cashier_id = auth.uid());
CREATE POLICY sale_items_read_authorized ON sale_items FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM sales s WHERE s.sale_id = sale_items.sale_id AND
    (current_app_role() IN ('administrator', 'manager') OR s.cashier_id = auth.uid())));
CREATE POLICY inventory_read_authorized ON inventory_movements FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager', 'inventory_staff'));
CREATE POLICY returns_read_authorized ON returns FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager') OR requested_by = auth.uid());
CREATE POLICY return_items_read_authorized ON return_items FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM returns r WHERE r.return_id = return_items.return_id AND
    (current_app_role() IN ('administrator', 'manager') OR r.requested_by = auth.uid())));
CREATE POLICY audit_read_admin_manager ON audit_logs FOR SELECT TO authenticated
USING (current_app_role() IN ('administrator', 'manager'));

