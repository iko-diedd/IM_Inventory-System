BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE TABLE schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TYPE app_role AS ENUM ('administrator', 'manager', 'cashier', 'inventory_staff');
CREATE TYPE purchase_status AS ENUM ('ordered', 'partially_received', 'received', 'cancelled');
CREATE TYPE sale_status AS ENUM ('completed', 'voided');
CREATE TYPE return_status AS ENUM ('pending', 'approved', 'rejected');
CREATE TYPE return_condition AS ENUM ('resalable', 'defective', 'damaged', 'pending_inspection');

CREATE TABLE app_profiles (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
    full_name TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
    role app_role NOT NULL DEFAULT 'cashier',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX categories_name_ci_idx ON categories (lower(name));

CREATE TABLE brands (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX brands_name_ci_idx ON brands (lower(name));

CREATE TABLE suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    contact_person TEXT,
    phone TEXT,
    email TEXT,
    address TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX suppliers_active_name_idx ON suppliers (lower(name)) WHERE is_active;

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE CHECK (length(trim(sku)) > 0),
    barcode TEXT UNIQUE,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    description TEXT,
    category_id BIGINT REFERENCES categories(category_id) ON DELETE RESTRICT,
    brand_id BIGINT REFERENCES brands(brand_id) ON DELETE RESTRICT,
    model TEXT,
    unit TEXT NOT NULL DEFAULT 'unit',
    average_cost NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (average_cost >= 0),
    selling_price NUMERIC(12,2) NOT NULL CHECK (selling_price >= 0),
    stock_quantity BIGINT NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    minimum_stock BIGINT NOT NULL DEFAULT 0 CHECK (minimum_stock >= 0),
    warranty_months INTEGER CHECK (warranty_months IS NULL OR warranty_months >= 0),
    specifications JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX products_name_idx ON products (lower(name));
CREATE INDEX products_stock_idx ON products (stock_quantity, minimum_stock) WHERE is_active;
CREATE INDEX products_category_idx ON products (category_id);
CREATE UNIQUE INDEX products_sku_ci_idx ON products (upper(sku));
CREATE UNIQUE INDEX products_barcode_ci_idx ON products (upper(barcode)) WHERE barcode IS NOT NULL;

CREATE TABLE supplier_products (
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    supplier_sku TEXT,
    last_unit_cost NUMERIC(12,2) CHECK (last_unit_cost IS NULL OR last_unit_cost >= 0),
    PRIMARY KEY (supplier_id, product_id)
);

CREATE TABLE purchases (
    purchase_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_number TEXT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id) ON DELETE RESTRICT,
    created_by UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    status purchase_status NOT NULL DEFAULT 'ordered',
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE purchase_items (
    purchase_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchases(purchase_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    ordered_quantity BIGINT NOT NULL CHECK (ordered_quantity > 0),
    received_quantity BIGINT NOT NULL DEFAULT 0 CHECK (received_quantity >= 0 AND received_quantity <= ordered_quantity),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    UNIQUE (purchase_id, product_id)
);

CREATE TABLE purchase_receipts (
    receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id BIGINT NOT NULL REFERENCES purchases(purchase_id) ON DELETE RESTRICT,
    idempotency_key UUID NOT NULL UNIQUE,
    received_by UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE purchase_receipt_items (
    receipt_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES purchase_receipts(receipt_id) ON DELETE RESTRICT,
    purchase_item_id BIGINT NOT NULL REFERENCES purchase_items(purchase_item_id) ON DELETE RESTRICT,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    UNIQUE (receipt_id, purchase_item_id)
);

CREATE TABLE sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number TEXT NOT NULL UNIQUE,
    idempotency_key UUID NOT NULL UNIQUE,
    cashier_id UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    discount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    tax NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (tax >= 0),
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    payment_method TEXT NOT NULL CHECK (payment_method IN ('cash', 'card', 'bank_transfer', 'other')),
    payment_status TEXT NOT NULL DEFAULT 'paid' CHECK (payment_status IN ('paid', 'refunded', 'partially_refunded')),
    status sale_status NOT NULL DEFAULT 'completed',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX sales_created_at_idx ON sales (created_at DESC);
CREATE INDEX sales_cashier_idx ON sales (cashier_id, created_at DESC);

CREATE TABLE sale_items (
    sale_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sales(sale_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    discount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    line_total NUMERIC(14,2) NOT NULL CHECK (line_total >= 0)
);
CREATE INDEX sale_items_product_idx ON sale_items (product_id, sale_id);

CREATE TABLE returns (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number TEXT NOT NULL UNIQUE,
    idempotency_key UUID NOT NULL UNIQUE,
    sale_id BIGINT NOT NULL REFERENCES sales(sale_id) ON DELETE RESTRICT,
    requested_by UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    approved_by UUID REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    status return_status NOT NULL DEFAULT 'pending',
    reason TEXT NOT NULL,
    refund_amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (refund_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ
);
CREATE INDEX returns_sale_idx ON returns (sale_id, status);

CREATE TABLE return_items (
    return_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL REFERENCES returns(return_id) ON DELETE RESTRICT,
    sale_item_id BIGINT NOT NULL REFERENCES sale_items(sale_item_id) ON DELETE RESTRICT,
    quantity BIGINT NOT NULL CHECK (quantity > 0),
    condition return_condition NOT NULL,
    inventory_disposition TEXT NOT NULL CHECK (inventory_disposition IN ('restock', 'do_not_restock')),
    refund_amount NUMERIC(14,2) NOT NULL CHECK (refund_amount >= 0),
    UNIQUE (return_id, sale_item_id),
    CHECK (
        (condition = 'resalable' AND inventory_disposition = 'restock')
        OR (condition <> 'resalable' AND inventory_disposition = 'do_not_restock')
    )
);

CREATE TABLE inventory_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    transaction_type TEXT NOT NULL CHECK (transaction_type IN ('purchase_receipt', 'sale', 'return', 'adjustment')),
    quantity_change BIGINT NOT NULL CHECK (quantity_change <> 0),
    previous_stock BIGINT NOT NULL CHECK (previous_stock >= 0),
    new_stock BIGINT NOT NULL CHECK (new_stock >= 0),
    source_type TEXT NOT NULL,
    source_id BIGINT NOT NULL,
    responsible_user UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (new_stock = previous_stock + quantity_change)
);
CREATE INDEX inventory_movements_product_date_idx ON inventory_movements (product_id, created_at DESC);
CREATE INDEX inventory_movements_date_idx ON inventory_movements (created_at DESC);

CREATE TABLE audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id UUID REFERENCES app_profiles(user_id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX audit_logs_created_idx ON audit_logs (created_at DESC);

CREATE FUNCTION prevent_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Audit records are immutable';
END;
$$;
CREATE TRIGGER audit_logs_no_update BEFORE UPDATE OR DELETE ON audit_logs
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

CREATE FUNCTION prevent_completed_sale_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = 'completed' THEN
        RAISE EXCEPTION 'Completed sales are immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER sales_no_completed_update BEFORE UPDATE ON sales
FOR EACH ROW EXECUTE FUNCTION prevent_completed_sale_mutation();
CREATE TRIGGER sale_items_no_update BEFORE UPDATE OR DELETE ON sale_items
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE TRIGGER inventory_movements_no_mutation BEFORE UPDATE OR DELETE ON inventory_movements
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE TRIGGER purchase_receipts_no_mutation BEFORE UPDATE OR DELETE ON purchase_receipts
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE TRIGGER purchase_receipt_items_no_mutation BEFORE UPDATE OR DELETE ON purchase_receipt_items
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE TRIGGER return_items_no_mutation BEFORE UPDATE OR DELETE ON return_items
FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();

CREATE FUNCTION protect_purchase_header() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.status IN ('received', 'cancelled')
       OR ROW(NEW.purchase_number, NEW.supplier_id, NEW.created_by, NEW.total_amount, NEW.notes, NEW.created_at)
          IS DISTINCT FROM
          ROW(OLD.purchase_number, OLD.supplier_id, OLD.created_by, OLD.total_amount, OLD.notes, OLD.created_at) THEN
        RAISE EXCEPTION 'Purchase history cannot be rewritten';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER purchases_protect_history BEFORE UPDATE OR DELETE ON purchases
FOR EACH ROW EXECUTE FUNCTION protect_purchase_header();

CREATE FUNCTION protect_purchase_item() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE'
       OR ROW(NEW.purchase_id, NEW.product_id, NEW.ordered_quantity, NEW.unit_cost)
          IS DISTINCT FROM
          ROW(OLD.purchase_id, OLD.product_id, OLD.ordered_quantity, OLD.unit_cost)
       OR NEW.received_quantity < OLD.received_quantity THEN
        RAISE EXCEPTION 'Purchase item history cannot be rewritten';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER purchase_items_protect_history BEFORE UPDATE OR DELETE ON purchase_items
FOR EACH ROW EXECUTE FUNCTION protect_purchase_item();

CREATE FUNCTION protect_return_decision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.status <> 'pending'
       OR ROW(NEW.return_number, NEW.idempotency_key, NEW.sale_id, NEW.requested_by, NEW.reason, NEW.refund_amount, NEW.created_at)
          IS DISTINCT FROM
          ROW(OLD.return_number, OLD.idempotency_key, OLD.sale_id, OLD.requested_by, OLD.reason, OLD.refund_amount, OLD.created_at)
       OR NEW.status NOT IN ('approved', 'rejected') THEN
        RAISE EXCEPTION 'Return history cannot be rewritten';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER returns_protect_history BEFORE UPDATE OR DELETE ON returns
FOR EACH ROW EXECUTE FUNCTION protect_return_decision();

