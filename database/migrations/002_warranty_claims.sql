BEGIN;

ALTER TABLE sale_items
    ADD COLUMN warranty_months INTEGER CHECK (warranty_months IS NULL OR warranty_months >= 0);

CREATE TABLE warranty_claims (
    warranty_claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_number TEXT NOT NULL UNIQUE,
    sale_item_id BIGINT NOT NULL REFERENCES sale_items(sale_item_id) ON DELETE RESTRICT,
    serial_number TEXT NOT NULL CHECK (length(trim(serial_number)) BETWEEN 1 AND 120),
    issue_description TEXT NOT NULL CHECK (length(trim(issue_description)) BETWEEN 1 AND 2000),
    warranty_expires_at DATE NOT NULL,
    requested_by UUID NOT NULL REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    decided_by UUID REFERENCES app_profiles(user_id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    resolution TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ,
    CHECK (
        (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL AND resolution IS NULL)
        OR (status IN ('approved', 'rejected') AND decided_by IS NOT NULL AND decided_at IS NOT NULL
            AND length(trim(COALESCE(resolution, ''))) > 0)
    )
);
CREATE UNIQUE INDEX warranty_claims_serial_ci_idx ON warranty_claims (upper(serial_number))
    WHERE status <> 'rejected';
CREATE INDEX warranty_claims_status_date_idx ON warranty_claims (status, created_at DESC);
CREATE INDEX warranty_claims_sale_item_idx ON warranty_claims (sale_item_id, status);

CREATE FUNCTION protect_warranty_claim_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.status <> 'pending'
       OR ROW(NEW.claim_number, NEW.sale_item_id, NEW.serial_number, NEW.issue_description,
              NEW.warranty_expires_at, NEW.requested_by, NEW.created_at)
          IS DISTINCT FROM
          ROW(OLD.claim_number, OLD.sale_item_id, OLD.serial_number, OLD.issue_description,
              OLD.warranty_expires_at, OLD.requested_by, OLD.created_at)
       OR NEW.status NOT IN ('approved', 'rejected')
       OR NEW.decided_by IS NULL OR NEW.decided_at IS NULL THEN
        RAISE EXCEPTION 'Warranty claim history cannot be rewritten';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER warranty_claims_protect_history
BEFORE UPDATE OR DELETE ON warranty_claims
FOR EACH ROW EXECUTE FUNCTION protect_warranty_claim_history();

ALTER TABLE warranty_claims ENABLE ROW LEVEL SECURITY;
CREATE POLICY warranty_claims_read_authorized ON warranty_claims FOR SELECT TO authenticated
USING (
    current_app_role() IN ('administrator', 'manager')
    OR (current_app_role() IS NOT NULL AND requested_by = auth.uid())
);
CREATE POLICY warranty_claims_trusted_backend ON warranty_claims FOR ALL TO inventory_app
USING (true) WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE ON warranty_claims TO inventory_app;
GRANT USAGE, SELECT ON SEQUENCE warranty_claims_warranty_claim_id_seq TO inventory_app;
GRANT SELECT ON warranty_claims TO authenticated;

INSERT INTO schema_migrations (version) VALUES ('002_warranty_claims') ON CONFLICT (version) DO NOTHING;

COMMIT;
